package app.slipnet.domain

import app.slipnet.domain.model.*
fun connectionChoiceRegression() {
    val ssh = ServerProfile(id=1, name="SSH", domain="example.org", tunnelType=TunnelType.SSH)
    val vless = ssh.copy(id=2, name="VLESS", isActive=true)
    val profiles = listOf(ssh,vless)
    check((ConnectionChoice.resolve(1,profiles) as ConnectionChoice.Target.Direct).profile.id == 1L)
    check(ConnectionChoice.resolve(null,profiles) == ConnectionChoice.Target.Automatic)
    check(ConnectionChoice.resolve(3,profiles) == ConnectionChoice.Target.Missing)
    val results = mapOf(2L to PingResult.Success(100,verified=true))
    check(ConnectionChoice.summaryProfileId(profiles,results,1,null) == 1L)
    check(ConnectionChoice.summaryProfileId(profiles,results,null,1) == 1L)
    check(ConnectionChoice.summaryProfileId(profiles,results,null,null) == 2L)
    check(ConnectionChoice.summaryProfileId(profiles,results,3,null) == null)
    check(ConnectionChoice.summaryProfileId(profiles,mapOf(1L to PingResult.Success(1)),null,null) == null)
    val dns = ssh.copy(id=4, tunnelType=TunnelType.DNSTT)
    val vlessPath = ssh.copy(id=5, tunnelType=TunnelType.VLESS)
    check(ConnectionChoice.initialPath(listOf(dns,ssh,vlessPath), emptyMap())?.id == 5L)
    check(ConnectionChoice.initialPath(listOf(dns), emptyMap()) == null)
    check(ConnectionChoice.initialPath(listOf(ssh,vlessPath), mapOf(1L to PingResult.Success(20,verified=true)))?.id == 1L)
    check(ConnectionChoice.initialPath(listOf(ssh), mapOf(1L to PingResult.Error("old HTTPS failure", measuredAt=0)))?.id == 1L)
    check(ConnectionChoice.initialPath(listOf(ssh), mapOf(1L to PingResult.Error("recent failure"))) == null)
    val connected = ConnectionState.Connected(ssh)
    check(ConnectionChoice.cardTap(false, false, ConnectionState.Disconnected,false) == ConnectionChoice.CardTap.SELECT)
    check(ConnectionChoice.cardTap(true, false, ConnectionState.Error("previous failure"),false) == ConnectionChoice.CardTap.CONNECT)
    check(ConnectionChoice.cardTap(false, false, connected,false) == ConnectionChoice.CardTap.SELECT)
    check(ConnectionChoice.cardTap(true, false, connected,false) == ConnectionChoice.CardTap.CONNECT)
    check(ConnectionChoice.cardTap(true, false, connected,true) == ConnectionChoice.CardTap.IGNORE)
    check(ConnectionChoice.cardTap(true, false, ConnectionState.Connecting,false) == ConnectionChoice.CardTap.IGNORE)
    check(ConnectionChoice.cardTap(true, true, ConnectionState.Disconnected,false) == ConnectionChoice.CardTap.IGNORE)
    println("PASS direct initial connection without ping, DNS consent boundary, explicit selection and historical measurement isolation")
}
