"""Convert the pinned public-domain SVG to native Avalonia vector drawings."""
from pathlib import Path
import json,re,xml.etree.ElementTree as ET
mac=Path(__file__).resolve().parents[1]
root=ET.fromstring((mac/'src/Rovunet.Desktop/Assets/iran-lion-sun.svg').read_bytes())
lines=['// Generated by scripts/generate-iran-flag.py; see licenses/Flags/SOURCE.txt.',
       'using Avalonia;','using Avalonia.Media;','namespace Rovunet.Desktop;',
       'static class IranFlagDrawing {',
       'static readonly Lazy<DrawingImage> source=new(Create);',
       'public static DrawingImage Source=>source.Value;',
       'static DrawingImage Create(){']
counter=0
def visit(element,parent,inherited):
    global counter
    counter+=1;name=f'd{counter}';tag=element.tag.split('}')[-1]
    style=dict(inherited)
    for key in ['fill','stroke','stroke-width','stroke-linejoin','stroke-linecap','fill-rule']:
        if key in element.attrib:style[key]=element.attrib[key]
    style.update(dict(part.split(':',1) for part in element.get('style','').split(';') if ':' in part))
    assert tag in ('svg','g','path'),tag
    if tag in ('svg','g'):
        lines.append(f'var {name}=new DrawingGroup();')
        if tag=='svg':assert element.get('viewBox')=='0 0 1050 600'
    else:
        brush='null' if style.get('fill','black')=='none' else 'Brush.Parse('+json.dumps(style.get('fill','black'))+')'
        pen='null' if style.get('stroke','none')=='none' else f'new Pen(Brush.Parse({json.dumps(style["stroke"])}),{style.get("stroke-width","1")})'
        lines.append(f'var {name}=new GeometryDrawing{{Geometry=Geometry.Parse({json.dumps(element.get("d"))}),Brush={brush},Pen={pen}}};')
    if element.get('transform'):
        fn,values=re.fullmatch(r'(matrix|translate)\(([^)]+)\)',element.get('transform')).groups()
        values=re.split(r'[ ,]+',values)
        if fn=='translate':values=['1','0','0','1',*values]
        assert len(values)==6
        lines.append(f'{name}.Transform=new MatrixTransform(new Matrix({",".join(values)}));' if tag!='path' else f'{name}.Geometry!.Transform=new MatrixTransform(new Matrix({",".join(values)}));')
    if parent:lines.append(f'{parent}.Children.Add({name});')
    for child in element:visit(child,name,style)
    return name
main=visit(root,None,{'fill':'black','stroke':'none'})
lines+=['return new DrawingImage{Drawing='+main+'};','}','}']
(mac/'src/Rovunet.Desktop/IranFlagDrawing.generated.cs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Generated native Iran flag drawing from 35 SVG paths')
